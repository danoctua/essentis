// Copies the self-hosted font subsets from @fontsource into public/fonts and writes src/styles/fonts.css.
// Run: node scripts/fonts.mjs (after npm install). Subsets cover Belarusian Cyrillic and Łacinka.
import { copyFileSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';

const RANGES = {
  cyrillic: 'U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116',
  'latin-ext': 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF',
  latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD',
};
const FAMILIES = [
  { family: 'IBM Plex Sans', pkg: 'ibm-plex-sans', faces: [[400, 'normal'], [500, 'normal']] },
  { family: 'IBM Plex Mono', pkg: 'ibm-plex-mono', faces: [[400, 'normal']] },
  { family: 'Alegreya', pkg: 'alegreya', faces: [[400, 'normal'], [500, 'normal'], [400, 'italic']] },
];

rmSync('public/fonts', { recursive: true, force: true });
mkdirSync('public/fonts', { recursive: true });
const css = ['/* Generated by scripts/fonts.mjs. Do not edit by hand. */'];
for (const { family, pkg, faces } of FAMILIES) {
  const dir = `node_modules/@fontsource/${pkg}/files`;
  const available = new Set(readdirSync(dir));
  for (const [weight, style] of faces) {
    for (const subset of Object.keys(RANGES)) {
      const file = `${pkg}-${subset}-${weight}-${style}.woff2`;
      if (!available.has(file)) throw new Error(`missing ${file}`);
      copyFileSync(`${dir}/${file}`, `public/fonts/${file}`);
      css.push(`@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:swap;src:url('/fonts/${file}') format('woff2');unicode-range:${RANGES[subset]}}`);
    }
  }
}
writeFileSync('src/styles/fonts.css', css.join('\n') + '\n');
console.log(`fonts: ${css.length - 1} faces`);
