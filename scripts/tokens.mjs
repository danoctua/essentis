// Writes src/styles/tokens.css from design/tokens.json (the brand book's tokens).
// Run: node scripts/tokens.mjs. Edit the brand book, copy its tokens.json to design/, rerun.
import { readFileSync, writeFileSync } from 'node:fs';

const t = JSON.parse(readFileSync('design/tokens.json', 'utf8'));
const ref = (v) => (typeof v === 'string' && /^\{[\w-]+\}$/.test(v) ? `var(--${v.slice(1, -1)})` : v);
const colorVars = (theme) =>
  t.color.tokens.map(({ name, value }) => `--${name}:${ref(typeof value === 'object' ? value[theme] : value)}`).join(';');

const light = colorVars('light');
const dark = colorVars('dark');
const fam = Object.entries(t.type.families).map(([k, v]) => `--font-${k}:${v}`).join(';');
const scalar = ['spacing', 'radius', 'layout'].flatMap((g) => t[g].tokens.map(({ name, value }) => `--${name}:${value}`)).join(';');

const typeClasses = t.type.groups.flatMap((g) =>
  g.styles.map((s) => {
    const p = [`font-family:var(--font-${g.family})`, `font-size:${s.fontSize}`, `line-height:${s.lineHeight}`, `font-weight:${s.fontWeight}`];
    if (s.letterSpacing) p.push(`letter-spacing:${s.letterSpacing}`);
    if (s.fontStyle) p.push(`font-style:${s.fontStyle}`);
    return `.type-${s.name}{${p.join(';')}}`;
  }),
);

const css = `/* Generated by scripts/tokens.mjs from design/tokens.json. Do not edit by hand. */
:root{color-scheme:light;${light};${fam};${scalar}}
@media (prefers-color-scheme: dark){:root:not([data-theme="light"]){color-scheme:dark;${dark}}}
:root[data-theme="dark"]{color-scheme:dark;${dark}}
${typeClasses.join('\n')}
`;
writeFileSync('src/styles/tokens.css', css);
console.log(`tokens: ${t.color.tokens.length} colours, ${typeClasses.length} type styles`);
